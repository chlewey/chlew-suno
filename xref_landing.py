"""Generate per-songbook appendices that land cross-songbook page references.

A song's notes may cite another song with \\pageref{sec:<slug>}.  When the cited
song is not part of the same songbook, the reference has no target.  For every
songbook this script writes xrefs/<book>.tex: an appendix chapter holding one
\\label{sec:<slug>} per missing target, saying which songbook(s) and album(s)
the song actually lives in.  Each songbook pulls it in with

    \\appendix
    \\input{xrefs/<book>}

just before \\backmatter (inserted by this script on first run).  Re-run it after
placing new songs: python xref_landing.py
"""
import re
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding='utf-8')
ROOT = Path(__file__).resolve().parent
OUT = ROOT / 'xrefs'

# book file stem -> display name, in the order books are listed in entries
BOOKS = {
    'entourage-eco': "Thomas' Entourage Soundtrack",
    'ricochets': 'Ricochets Soundtrack',
    'stories': 'Stories Songbook',
    'internal': 'Internal and Non-Fiction Songbook',
    'personal': 'Personal Songbook',
    'original': 'Original Lyrics Songbook',
    'generos': 'By Genre Songbook',
    'electronica': 'Electronica Soundtrack',
    'pop': 'Pop Songbook',
    'rockola': 'Rock Songbook',
    'chlewrics': 'The Complete Collection',
}
SONG_DIRS = ['chlewey', 'dvigitt', 'gabisson', 'rataflechera', 'temp', 'wyomee']

INCLUDE_RE = re.compile(r'^\s*\\(?:input|include)\{([^}]+)\}')
CHAPTER_RE = re.compile(r'^\s*\\chapter\{(.*)\}\s*$')
LABEL_RE = re.compile(r'\\label\{(sec:[^}]+)\}')
REF_RE = re.compile(r'\\pageref\{(sec:[^}]+)\}')
TITLE_RE = re.compile(r'\\songtitle\{(.*)\}')
HOOK = ['\\appendix', '\\input{xrefs/%s}']


def read(p):
    return p.read_bytes().decode('utf-8')


def songs_of(stem):
    """[(song path stem, album)] reached from a book, expanding \\include'd parts."""
    out, album = [], None
    for line in read(ROOT / f'{stem}.tex').splitlines():
        m = CHAPTER_RE.match(line)
        if m:
            album = m.group(1)
            continue
        m = INCLUDE_RE.match(line)
        if not m:
            continue
        target = m.group(1)
        if '/' in target:
            out.append((target, album))
        elif (ROOT / f'{target}.tex').exists():
            out += songs_of(target)
    return out


song_text = {}
label_owner = {}
for d in SONG_DIRS:
    for p in sorted((ROOT / d).glob('*.tex')):
        s = f'{d}/{p.stem}'
        song_text[s] = t = read(p)
        for l in LABEL_RE.findall(t):
            label_owner.setdefault(l, s)

contents = {b: songs_of(b) for b in BOOKS}
where = {}  # song -> [(book, album)]
for b, songs in contents.items():
    for s, album in songs:
        where.setdefault(s, [])
        if (b, album) not in where[s]:
            where[s].append((b, album))


def title(s):
    m = TITLE_RE.search(song_text.get(s, ''))
    return m.group(1) if m else s


def entry(label, owner, book):
    places = [(b, a) for b, a in where.get(owner, []) if b != book]
    # The Complete Collection only when nothing more specific exists
    specific = [(b, a) for b, a in places if b != 'chlewrics']
    places = specific or places
    if places:
        loc = '; '.join(f'\\emph{{{BOOKS[b]}}}' + (f', album \\emph{{{a}}}' if a else '')
                        for b, a in places)
    else:
        loc = 'not yet placed in any songbook'
    return f'\\item[{title(owner)}]\\label{{{label}}} {loc}.'


OUT.mkdir(exist_ok=True)
report = []
for b, songs in contents.items():
    present = {s for s, _ in songs}
    labels = {l for s in present for l in LABEL_RE.findall(song_text.get(s, ''))}
    missing = {}
    for s in present:
        for r in REF_RE.findall(song_text.get(s, '')):
            if r not in labels and r in label_owner:
                missing.setdefault(r, label_owner[r])
            elif r not in label_owner:
                report.append(f'!! {b}: {s} cites {r}, which no song defines')
    lines = [f'% Generated by xref_landing.py -- do not edit by hand.']
    if missing:
        lines += [
            '\\chapter{Songs in Other Songbooks}',
            'Some notes in this songbook point to songs that live elsewhere in the collection. '
            'Their page references land here, with where to find each song.',
            '\\begin{description}',
            *sorted((entry(l, o, b) for l, o in missing.items()), key=str.casefold),
            '\\end{description}',
        ]
    (OUT / f'{b}.tex').write_bytes(('\n'.join(lines) + '\n').encode('utf-8'))
    report.append(f'{b:14} {len(missing):3} landing label(s)')

    # hook the appendix into the book once, before \backmatter
    p = ROOT / f'{b}.tex'
    t = read(p)
    eol = '\r\n' if '\r\n' in t else '\n'
    hook = [HOOK[0], HOOK[1] % b]
    if hook[1] not in t:
        ls = t.split(eol)
        i = ls.index('\\backmatter')
        ls[i:i] = hook
        p.write_bytes(eol.join(ls).encode('utf-8'))
        report.append(f'{"":14} hooked xrefs/{b} into {b}.tex')

print('\n'.join(report))
